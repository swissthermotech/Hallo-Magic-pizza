export type StringKey = keyof typeof STRINGS.fr;

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: StringKey) => string;
  tx: (v: I18nText | undefined | null) => string;
}

const Ctx = createContext<I18nCtx>({ lang: "fr", setLang: () => {}, t: (k) => STRINGS.fr[k], tx: (v) => v?.fr ?? "" });

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");
  useEffect(() => {
    storage.getItem<string>("lang", "fr").then((v) => {
      if (v === "de" || v === "fr") setLangState(v);
    });
  }, []);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    storage.setItem("lang", l);
  }, []);
  const value = useMemo<I18nCtx>(
    () => ({
      lang,
      setLang,
      t: (k) => STRINGS[lang][k] ?? STRINGS.fr[k],
      tx: (v) => (v ? v[lang] || v.fr : ""),
    }),
    [lang, setLang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);

export function statusLabel(status: OrderStatus, type: OrderType, t: (k: StringKey) => string): string {
  if (status === "ready") return type === "pickup" ? t("status_ready_pickup") : t("status_ready_delivery");
  return t(`status_${status}` as StringKey);
}

